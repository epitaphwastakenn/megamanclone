const glyphCache = new Map();

// FUNCTIONS

function getGlyphCanvas(ch, color) {
  const key = ch + color;
  let canvas = glyphCache.get(key);
  if (canvas) return canvas;
  canvas = document.createElement('canvas');
  canvas.width = 8;
  canvas.height = 8;
  const glyph = fontGlyphs[ch];
  if (glyph) {
    const ctx = canvas.getContext('2d');
    ctx.fillStyle = color;
    for (let y = 0; y < glyph.length; y++) {
      for (let x = 0; x < glyph[y].length; x++) {
        if (glyph[y][x] === '#') ctx.fillRect(x, y, 1, 1);
      }
    }
  }
  glyphCache.set(key, canvas);
  return canvas;
}

function drawText(ctx, text, x, y, color, scale) {
  const size = scale || 1;
  const fill = color || nesPalette[0x30];
  let cursorX = x;
  for (const ch of String(text).toUpperCase()) {
    if (ch !== ' ') ctx.drawImage(getGlyphCanvas(ch, fill), Math.round(cursorX), Math.round(y), 8 * size, 8 * size);
    cursorX += 8 * size;
  }
}

function drawTextCentered(ctx, text, centerX, y, color, scale) {
  const width = String(text).length * 8 * (scale || 1);
  drawText(ctx, text, Math.round(centerX - width / 2), y, color, scale);
}
